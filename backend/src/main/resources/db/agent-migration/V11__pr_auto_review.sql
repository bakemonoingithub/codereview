-- PR 自动审查：项目配置与 Webhook 投递处理记录（PRA-02）
CREATE TABLE pr_auto_review_config (
    id                CHAR(26)      NOT NULL,
    project_id        CHAR(26)      NOT NULL,
    enabled           TINYINT       NOT NULL DEFAULT 0,
    target_branch     VARCHAR(200)  NOT NULL DEFAULT 'main',
    model_config_id   CHAR(26)      NULL,
    prompt_id         CHAR(26)      NULL,
    prompt_version_id CHAR(26)      NULL,
    review_base_url   VARCHAR(500)  NULL,
    webhook_secret    VARCHAR(256)  NULL,
    reviewers         JSON          NULL,
    bot_actor_id      BIGINT        NULL,
    bot_login         VARCHAR(100)  NULL,
    repo_id           BIGINT        NULL,
    repo_full_name    VARCHAR(500)  NULL,
    created_at        DATETIME(3)   NOT NULL,
    updated_at        DATETIME(3)   NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_pra_config_project (project_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE pr_auto_review_delivery (
    id                   CHAR(26)      NOT NULL,
    host_type            VARCHAR(16)   NULL,
    host_instance_key    VARCHAR(500) COLLATE utf8mb4_bin NULL,
    delivery_id          VARCHAR(64)   NULL,
    first_received_at    DATETIME(3)   NOT NULL,
    last_received_at     DATETIME(3)   NOT NULL,
    receive_count        INT           NOT NULL DEFAULT 1,
    event_name           VARCHAR(100)  NULL,
    event_type           VARCHAR(100)  NULL,
    event_action         VARCHAR(100)  NULL,
    repo_id              BIGINT        NULL,
    repo_full_name       VARCHAR(500)  NULL,
    pr_number            BIGINT        NULL,
    actor_user_id        BIGINT        NULL,
    actor_login          VARCHAR(100)  NULL,
    source_comment_id    BIGINT        NULL,
    payload_snapshot     JSON          NULL,
    project_id           CHAR(26)      NULL,
    trigger_kind         VARCHAR(16)   NULL,
    target_branch        VARCHAR(200)  NULL,
    decision_state       VARCHAR(16)   NOT NULL DEFAULT 'RECEIVED',
    decided_at           DATETIME(3)   NULL,
    decision_code        VARCHAR(64)   NULL,
    decision_message     VARCHAR(500)  NULL,
    business_key         VARCHAR(100)  NULL,
    canonical_record_id  CHAR(26)      NULL,
    task_request_snapshot JSON         NULL,
    source_head          VARCHAR(64)   NULL,
    target_head          VARCHAR(64)   NULL,
    merge_base           VARCHAR(64)   NULL,
    text_count           INT           NULL,
    binary_count         INT           NULL,
    unreadable_count     INT           NULL,
    review_task_id       CHAR(26)      NULL,
    review_url           VARCHAR(1024) NULL,
    comment_actor_id     BIGINT        NULL,
    comment_body         TEXT          NULL,
    comment_attempts     INT           NOT NULL DEFAULT 0,
    comment_last_attempt_at DATETIME(3) NULL,
    comment_state        VARCHAR(16)   NOT NULL DEFAULT 'NONE',
    comment_id           BIGINT        NULL,
    comment_http_status  SMALLINT      NULL,
    comment_error        VARCHAR(500)  NULL,
    comment_checked_at   DATETIME(3)   NULL,
    revision             INT           NOT NULL DEFAULT 0,
    lease_until          DATETIME(3)   NULL,
    next_attempt_at      DATETIME(3)   NULL,
    updated_at           DATETIME(3)   NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_delivery (host_type, host_instance_key, delivery_id),
    UNIQUE KEY uk_project_business_key (project_id, business_key),
    KEY idx_project_received (project_id, first_received_at, id),
    KEY idx_host_repo_pr (host_type, host_instance_key, repo_id, pr_number, first_received_at, id),
    KEY idx_review_task_id (review_task_id),
    KEY idx_canonical_record (canonical_record_id),
    KEY idx_next_attempt (next_attempt_at, id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
